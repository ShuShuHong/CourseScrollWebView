def master_prompt(style):
    return STYLES[style]['look'] + BASE + MALE + FEMALE + TAIL_MASTER + NEG


def stage_text(sex, stage):
    s = STAGE[stage]
    if callable(s):
        return s(sex)
    if isinstance(s, dict):
        return s[sex]
    return s


def variant_prompt(style, vid):
    sex, stage, mood = VARIANTS[vid]
    st = stage_text(sex, stage)
    who = MALE if sex == 'm' else FEMALE
    keep = (
        "参考图2 这只角色的身体必须原样保留：同样的头身比、同样大的圆脑袋、同样的圆壳轮廓与配色、"
        "同样形状的六条短腿、同样形状的两只圆手套大螯、同样的眼睛位置与眼柄长度、同一套画风与白色描边；"
        "只允许改动下面列出的服装与动作，不要重画身体、不要改变体型胖瘦、不要改变五官大小。"
    )
    tail = ("画面中只有这一只角色，全身完整，居中，纯白色背景，背景无任何元素，地面无投影。" + BACK_VIEW) if vid in BACK_IDS else TAIL_SINGLE
    return keep + LEGS + STYLES[style]['look'] + BASE + who + st + MOOD[mood] + tail + NEG


